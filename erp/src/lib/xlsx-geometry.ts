/** 엑셀 격자 기하 — 열 폭·행 높이를 **픽셀**로 옮기는 단 한 벌의 자.
 *
 *  ## 왜 따로 떼어 놓는가
 *
 *  그림을 칸 안에 앉히는 코드가 둘이다(`fire-plan-xlsx-images` · `defect-photo-embed`).
 *  둘이 다른 산식을 쓰면 같은 그림이 시트마다 다른 자리에 놓인다. 종전엔 「같은 산식을 쓸 것」을
 *  **주석으로만** 약속했고, 그 약속된 산식 자체가 틀려 있었다.
 *
 *  ## 무엇이 틀렸었나 (2026-09-21 실측)
 *
 *  종전 산식은 `px = round(width × 7 + 5)`였다. `+5`는 **칸 하나의 안쪽 여백**(좌우 2px +
 *  격자선 1px)인데, 이걸 **열마다** 더한 것이 결함이다. 열이 넓을 땐 오차가 묻히지만
 *  소방계획서 표지처럼 **1.8자짜리 미세 격자 60열**을 합치면 유령 폭이 300px 생긴다:
 *
 *      열 하나   18px(틀림) vs 13px(맞음)
 *      60열 상자 1080px(틀림) vs 780px(맞음)
 *
 *  그 결과 표지 사진이 가운데로 간다고 믿으면서 실제로는 **왼쪽으로 160px 밀려** 앉았고,
 *  16:9 사진은 오른쪽으로 **넘쳐 잘렸다**(여백 -104px). 사용자가 두 번 「사진이 가운데가
 *  아니다」라고 지적한 것이 이 결함이다.
 *
 *  🚨 **계산이 내부적으로 일관돼도 기준이 틀리면 전부 틀린다.** 종전 코드는 상자 폭도
 *    오프셋도 같은(틀린) 자로 쟀기 때문에 «대칭»으로 보였다 — 산식을 베껴 쓴 검사도 같이 속았다.
 *    그래서 이 자의 정답은 **Excel 규격식**으로 못박고, 검사는 산출물을 열어서 잰다.
 */

/** 기본 글꼴의 '0' 글자 폭(px) — 엑셀 규격의 MDW(Maximum Digit Width). 맑은 고딕 11pt 기준 7 */
const MDW = 7

/**
 * 열 폭(엑셀 '문자' 단위) → 픽셀. **규격식**이다:
 *
 *     px = Truncate( ( (256 × width + Truncate(128 / MDW)) / 256 ) × MDW )
 *
 * 실측 대조: `width="1.80"` → 13px. (종전 `round(1.8×7+5)`는 18px로 **5px 부풀었다**.)
 */
export function colWidthToPx(width: number): number {
  return Math.floor(((256 * width + Math.floor(128 / MDW)) / 256) * MDW)
}

/** 행 높이(pt) → 픽셀. 96dpi ÷ 72pt = 4/3 (여기는 종전과 같다 — 틀린 적이 없다) */
export function rowHeightToPx(pt: number): number {
  return Math.round(pt * 4 / 3)
}
