/** **용도(주용도) 표기 축** — 소방계획서_47 B-15 · 단일 원천.
 *
 *  값이 아니라 **표기만** 바꾸는 자리다(47 S5-2와 같은 축). 원천은 언제나 건축물대장 그대로의
 *  `buildings.purpose`(`제2종근린생활시설`)이고, 산출물의 칸 폭·납품 관례에 따라 두 가지로 편다.
 *
 *  ⭐ **왜 별도 파일인가** — 종전에는 이 셋이 `fire-plan-xlsx-values.ts`에 있었다. 거기서
 *    그대로 import 하면 HTML(PDF) 경로가 `fire-plan-anchors` → `fire-plan-xlsx-manifest`까지
 *    물고 오고, manifest의 `labelAt`은 **모듈 적재 시점에 throw** 한다(좌표가 밀리면). 즉
 *    엑셀 격자가 흔들릴 때 PDF까지 500이 된다. 표기 규칙은 격자와 아무 상관이 없으므로
 *    **의존이 없는 소모듈**로 떼어 둔다(같은 47의 `fire-plan-align.ts` 선례).
 *    ⚠ 이 파일은 `server-only`를 물지 않는다 — 클라이언트·스크립트에서도 쓸 수 있어야 한다.
 *
 *  ── 규칙의 유래 ─────────────────────────────────────────────────────────
 *  ERP는 건축물대장 그대로 `제2종근린생활시설`(9자)을 갖고 있는데 엑셀 서식 1.1의 주용도 칸이
 *  그만큼 넓지 않다 — 두 줄로 접히면서 옆 칸(사용승인일)까지 밀어낸다. 강순기 실납품본은 이
 *  칸을 **`근생`**으로 줄여 적었고(D-4 = 강순기가 정답지), 사용자도 그렇게 지시했다(2026-09-08).
 *  반면 **표지·PDF·3.1·1.11.4는 `근린생활시설`**이다 — 한 문서가 같은 값을 자리마다 다르게
 *  적는 것이고, 그건 원본이 그렇다(F-14 대조 · 사용자 확정 2026-09-09).
 *
 *  ⚠ **제2종만 줄이면 제1종이 다음에 똑같이 넘친다.** 근린생활시설 갈래를 함께 넣는다
 *    (`근생`은 원래 그 갈래 전체의 통용 약어다). 오늘 DB엔 제2종 3건뿐이지만 제1종은
 *    건축법 분류에 실재하므로 들어올 수 있다.
 *  ⚠ `문화및집회시설`(7자)은 **줄이지 않는다** — 통용되는 약어가 없어 우리가 지어내는 것이
 *    되고, 법정 기재사항을 임의로 축약하는 셈이다. 넘치면 그때 별도로 판단한다.
 *
 *  🚨 2026-09-08 실측으로 드러났던 것: 주석은 「표지는 근린생활시설」이라 적어 두었는데 정작
 *     코드는 원값을 그대로 넘겨 `제2종근린생활시설`을 찍고 있었다. 주석이 목표값을 말하면서
 *     그 값을 만드는 함수가 없었던 것 — **의도와 산출이 갈라져 있었다.** 그래서 갈래 목록을
 *     하나로 두고 **표기 두 가지를 거기서 파생**시킨다. 종류가 늘어도 한 곳만 고친다.
 */

/** `fire-plan-xlsx-values.ts`의 `txt`와 같은 규약 — 공백 정리 + `'0'`은 미입력으로 본다 */
const norm = (v: string | number | null | undefined): string => {
  if (v === null || v === undefined) return ''
  const s = String(v).trim()
  return s === '0' ? '' : s
}

/** 근린생활시설 갈래 — 표기 두 가지가 **여기 하나**에서 갈라진다 */
export const NEIGHBORHOOD_FACILITY = new Set(['제1종근린생활시설', '제2종근린생활시설'])

/** 근린생활시설 갈래인가 — 검사·호출부가 목록을 베끼지 않도록 판정을 함께 내보낸다 */
export function isNeighborhoodFacility(v: string | null | undefined): boolean {
  return NEIGHBORHOOD_FACILITY.has(norm(v))
}

/**
 * 좁은 칸(**엑셀 서식 1.1 주용도 · 1.2.1 구역 용도**)용 표기 — 갈래는 `근생`으로 줄인다.
 *
 * ⚠ 이 두 자리는 **엑셀 전용**이다. PDF는 칸 폭 제약이 없어 `purposeCover`를 쓴다
 *   (사용자 확정 2026-09-09). 갈래가 아니면 원값을 그대로 통과시킨다.
 */
export function purposeShort(v: string | null | undefined): string {
  const s = norm(v)
  return NEIGHBORHOOD_FACILITY.has(s) ? '근생' : s
}

/**
 * 넓은 칸용 표기 — 갈래는 밝히되 `제N종`은 떼어낸다(강순기 표지·납품본이 그렇다).
 *
 * 쓰는 자리: 엑셀 **표지·3.1 용도·1.11.4 용도**, PDF **1.1 주용도·1.2.1 명칭/용도·3.1 용도**.
 * 갈래가 아니면 원값을 그대로 통과시킨다 — 사람이 직접 적은 구역명(`사무실`·`1~2층`)이
 * 이 함수를 지나가도 손대지 않는 이유가 이것이다.
 */
export function purposeCover(v: string | null | undefined): string {
  const s = norm(v)
  return NEIGHBORHOOD_FACILITY.has(s) ? '근린생활시설' : s
}
