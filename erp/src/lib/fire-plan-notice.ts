/** 엑셀 고지를 **클릭할 수 있는 조각**으로 쪼갠다 (2026-09-21 사용자 요청 「엑셀 생성을 쉽게」).
 *
 *  ■ 왜 필요한가
 *  소방계획서 엑셀 라우트는 `X-FirePlan-Missing` 헤더로 빠진 것을 말해 준다
 *  (「선임현황(1.7.1) 2명 미표기(양식 16행)」처럼). 그런데 화면은 그걸 **`<p>` 한 덩어리**로
 *  그렸다 — 읽고 나서 사용자가 그 서식을 **직접 찾아가야** 했다. 바로 옆 「누락 칩」은
 *  누르면 입력처로 데려다 주는데, 정작 엑셀이 지적한 자리는 클릭이 안 됐다.
 *  이걸 칩으로 만들면 고리가 닫힌다: 입력 → 엑셀 → 「1.7.1이 비었다」 → 클릭 → 그 칸 → 다시 엑셀.
 *
 *  ■ 🚨 접두를 잘라 추측하면 안 된다
 *  고지가 말하는 번호는 **시트 번호**이고 화면 노드 키와 다르다.
 *    `1.7.1` → 노드 `1.7`   (뒤를 자르면 맞는다 — 우연이다)
 *    `1.15`  → 노드 **`1.12`**  (뒤를 자르면 `1.1`이 나온다. `1.1`은 실재하는 **엉뚱한** 노드다)
 *  그래서 자르지 않고 **대장이 만든 표**(`SHEET_NO_TO_FORM`)에만 묻는다. 표에 없으면 칩을
 *  만들지 않는다 — 지어낸 목적지로 보내느니 **글자로 남기는 게 낫다**.
 *
 *  ■ 못 알아보면 조용히 글자로 남는다
 *  라우트의 고지 문구는 자유 서술이라 번호가 없는 것도 많다(「구역별 세부현황 3개 구역 미표기」).
 *  그런 조각은 `form`이 없는 채로 돌아가고 화면은 그냥 글자로 그린다 — **종전과 같은 모습**이다.
 *  즉 이 기능은 최악의 경우에도 종전으로 되돌아갈 뿐, 깨지지 않는다.
 */
import { SHEET_NO_TO_FORM } from '@/lib/fire-plan-notice-map'
import type { FirePlanFormKey } from '@/lib/fire-plan-sections'

/** 라우트가 조각을 잇는 구분자 (`noticeHeader`의 `join(' | ')`) */
const SEP = ' | '

/** 번호처럼 생긴 토큰 — `1.7.1`·`2.10`·`3.3`. 뒤에 숫자가 더 붙는 경우까지 통째로 집는다.
 *  ⚠ `(양식 16행)`·`50명` 같은 홑숫자는 **애초에 걸리지 않는다**(점이 있어야 한다).
 *
 *  🚨 **뒤에 한글이 붙으면 서식 번호가 아니다.** 고지에는 사용자가 입력한 장소명이 그대로 실린다
 *    (`화재취약장소 2곳 미표기(양식 고정 3개소 밖): 보일러실 3.5층창고`). 그 「3.5」는 **실재하는
 *    시트 번호**(3.5 → ch3)라, 이 가드가 없으면 창고 이름을 읽고 3장 피난계획으로 보낸다.
 *    실제 고지에서 서식 번호는 늘 `)`·`·`·공백·문장끝이 뒤따른다(`(1.7.1)`·`1.6.1·2.12`).
 *    검사 [2]의 「3.5층창고」 표본이 이 규칙을 붙들고 있다. */
const NO_TOKEN = /\d+(?:\.\d+)+(?![0-9]|[가-힣])/g

/* ⚠ 종전에 방어를 하나 더 뒀다가 **걷어냈다**: 「콜론 뒤(사용자 입력 목록)는 훑지 않는다」.
     변이 N3(그 절단을 무력화)가 **생존**해서 드러났다 — 위 한글 가드가 이미 같은 일을 하고 있어
     **죽은 방어**였다. 게다가 해로운 쪽이었다: 콜론 뒤가 사용자 값이 아니라 **진짜 시트 좌표**인
     고지가 있다(「서식 좌표 자가치유: 1.4!AR13」·「체크박스 미적용 5칸(…): 1.7.1!AR13」).
     절단하면 그 옳은 링크까지 막는다 — 되살리지 말 것. */

export type NoticePart = {
  /** 사용자에게 보여 줄 문장 그대로 */
  text: string
  /** 이 조각이 가리키는 화면 노드 — 표에 없으면 undefined(= 칩이 아니라 글자) */
  form?: FirePlanFormKey
  /** 칩에 찍을 번호 (`1.7.1`) — form이 있을 때만 */
  no?: string
}

/** 고지 한 덩어리를 조각으로. 빈 문자열이면 빈 배열(호출부가 분기하지 않게). */
export function parseFirePlanNotice(raw: string): NoticePart[] {
  if (!raw.trim()) return []
  return raw.split(SEP).map(s => s.trim()).filter(Boolean).map(text => {
    // 한 조각에 번호가 여럿일 수 있다(「위험물 … (양식 3행 — 1.6.1·2.12 공통)」).
    // **먼저 나오는** 인식 가능한 번호를 쓴다 — 문장의 주어에 가까운 쪽이다.
    for (const m of text.match(NO_TOKEN) ?? []) {
      const form = SHEET_NO_TO_FORM[m]
      if (form) return { text, form, no: m }
    }
    return { text }
  })
}

/** 칩으로 만들 수 있는 조각 수 — 「이 고지에 갈 곳이 있는가」를 화면이 한 번에 묻게 한다 */
export function clickableCount(parts: NoticePart[]): number {
  return parts.filter(p => p.form).length
}
