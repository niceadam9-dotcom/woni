/** 저장 어휘(별지9호 표기)를 그 서식의 원문 표기로 바꾼다 — 출력 직전에만 부른다. */
export function annexLabel(form: AnnexForm, canonical: string): string {
  return form === 'annex4' ? (ANNEX4_LABELS[canonical] ?? canonical) : canonical
}

/** 그 서식 원문에 이 항목의 행이 있는가 — 없으면 렌더에서 뺀다. */
export function annexHasItem(form: AnnexForm, canonical: string): boolean {
  return form === 'annex4' ? !ANNEX4_ABSENT.has(canonical) : true
}

