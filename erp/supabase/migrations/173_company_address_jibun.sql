-- 173: 회사정보 지번 주소 (통합 실행계획 C5 2차, 2026-10-02)
--
-- 배경(실측): 갑지·소방계획서 엑셀 템플릿에 운영사 정보가 26칸 리터럴로 박혀 있다(갑지 14·소방계획서 12).
--   그중 주소가 두 꼴이다 — 도로명+지번 괄호「경기도 양평군 양평읍 잿말길10번길 50-1 (덕평리 98-1)」(완료보고서)와
--   지번 전체「경기도 양평군 양평읍 덕평리 98-1」(소방계획서 서식 1.8 업무대행 현황 업체주소).
--   회사정보에는 도로명 주소 한 칸뿐이라(그마저 운영값이 「잿말길 50-1」로 템플릿의 「10번길」과 달랐다 —
--   사용자 확인: 템플릿이 맞다) 지번 꼴을 만들 원천이 없었다.
--
-- 이 열은 **지번 주소 전체**를 담는다(예: 「경기도 양평군 양평읍 덕평리 98-1」).
--   완료보고서의 괄호 꼴은 도로명과 지번의 공통 머리(시·도 시·군·구 읍·면·동 앞)를 떼어 조립한다(lib/company-literals).
--   비우면 지번 칸은 도로명 주소로 대신한다.
-- 새 열이라 백필 없음. 운영·스테이징 값은 적용 직후 회사정보로 채운다(_apply-173-both.mjs).

ALTER TABLE company_profile ADD COLUMN IF NOT EXISTS address_jibun TEXT;

COMMENT ON COLUMN company_profile.address_jibun IS
  '지번 주소 전체(예: 경기도 양평군 양평읍 덕평리 98-1) — 소방계획서 1.8 업체주소·완료보고서 괄호 지번의 원천. 비우면 도로명 주소로 대신 (173, C5)';
