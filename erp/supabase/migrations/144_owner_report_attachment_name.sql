-- 관계인 보고 메일의 첨부 파일명을 별지 9호 저장명 규약에 맞춘다 (2026-08-20 사용자 확정).
--   종전: {고객명}_자체점검결과보고서
--   변경: {연도}_소방시설등 자체점검_실시결과보고서_{고객명}
--
-- 같은 문서(별지 9호)가 화면에서는 새 규약으로, 메일에서는 옛 이름으로 나가던 어긋남을 없앤다.
-- 화면 내려받기 쪽 규약은 코드(lib/annex-filename.ts)에 있고, 여기는 **사용자가 설정에서 고칠 수 있는 값**이다.
--
-- ⚠ 조건부 UPDATE다 — 130 시드 그대로인 행만 바꾼다. 관리자가 이미 손으로 고쳐 둔 문구가 있으면
--   그건 사용자의 선택이므로 덮지 않는다(설정 화면에서 바꾸면 된다).
UPDATE message_templates
   SET attachment_name = '{연도}_소방시설등 자체점검_실시결과보고서_{고객명}',
       updated_at = NOW()
 WHERE key = 'owner_report'
   AND attachment_name = '{고객명}_자체점검결과보고서';
