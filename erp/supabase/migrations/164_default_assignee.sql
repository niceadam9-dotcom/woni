-- 164: 기본 담당자 + 배정 출처 — 「일반관리」 고객이 미배정으로 남는 것을 막는다 (2026-09-15 사용자 결정)
--
-- 배경(운영 화면 image-16, 해오름어린이집): 「일반」 유형 고객의 담당직원이 **미배정**으로 남는다.
--   스테이징 실측 — 활성 304명 중 미배정 36명. 그중 「일반관리」는 2명(민박점검·양평군가족센터)이고
--   나머지 34명은 작동/종합이며 **전원 영업권(양평군) 밖**이다(홍천군 22·군부대 다수). 원인이 둘이라
--   이 마이그레이션은 **「일반관리」 축만** 다룬다. 영업권 밖 축은 별건(지역별 배정 화면으로 처리).
--
-- 왜 「일반관리」인가: 1회성 점검이라 담당을 정하는 절차 자체가 없다. 실측상 5명 중 3명은 이미
--   대표(김흥준)에게 배정돼 있어 **관행이 이미 그러하다** — 규칙으로 못 박는 일이다.

-- ── ① 기본 담당자 (회사 설정) ──────────────────────────────────────────────────
-- `company_profile.representative`를 쓰지 않는 이유: 그건 **이름 문자열**이라 profiles와 이어져
-- 있지 않다. 동명이인·개명·퇴사에서 조용히 끊긴다. 또 「대표자」와 「기본 담당자」는 원래 다른
-- 개념이고, 사용자가 직접 고르기로 했다(2026-09-15). 같은 테이블의 default_region_si가 선례다.
--
-- ON DELETE SET NULL — 그 직원이 사라지면 설정이 비는 것이 옳다. RESTRICT면 퇴사 처리가 막히고,
-- CASCADE는 회사 프로필 행을 지운다(둘 다 이 축이 감당할 일이 아니다).
ALTER TABLE company_profile
  ADD COLUMN IF NOT EXISTS default_assignee_id UUID REFERENCES profiles(id) ON DELETE SET NULL;

COMMENT ON COLUMN company_profile.default_assignee_id IS
  '기본 담당자 — 「일반관리」 고객이 담당 미선택으로 저장될 때 자동으로 채울 직원. '
  'NULL이면 자동 채움을 하지 않는다(종전 동작: 미배정 그대로). 정식 배정과 달리 알림을 보내지 않는다.';

-- ── ② 배정 출처 ────────────────────────────────────────────────────────────────
-- 미배정을 채우기만 하면 **문제를 고치는 게 아니라 숨기는 것**이 된다. 지금 빨간 「미배정」이
-- "담당이 정해지지 않았다"를 알리는 유일한 신호이기 때문이다. 그 신호를 잃지 않으려면
-- 「사람이 고른 것」과 「기본값으로 채운 것」을 갈라야 한다 — 그것이 이 컬럼이다.
--
-- 값: 'manual'(사람이 고름) / 'default'(기본 담당자로 자동 채움) / NULL(미배정이거나 출처 미상).
-- ⚠ 코드는 **'default'일 때만** 「(기본)」을 표시한다. 그래서 NULL은 자동으로 manual처럼 동작하고,
--   이 컬럼을 못 읽는 옛 경로가 남아 있어도 없던 표식이 생기지 않는다(안전한 방향으로 퇴화한다).
ALTER TABLE customers ADD COLUMN IF NOT EXISTS assigned_source TEXT;

COMMENT ON COLUMN customers.assigned_source IS
  '담당 배정의 출처: manual=사람이 고름 / default=기본 담당자로 자동 채움 / NULL=미배정·출처 미상. '
  '화면은 default일 때만 「(기본)」을 붙인다. 나중에 정식 배정으로 바꿀 대상을 찾는 유일한 축이다.';

-- 백필 — 지금까지 배정된 것은 전부 사람이 고른 것이다(기본 배정 경로가 오늘 처음 생긴다).
-- ⚠ 이 백필은 **동작을 바꾸지 않는다**. 코드가 'default'만 보므로 NULL로 두어도 결과가 같다.
--   그럼에도 채우는 것은 데이터가 스스로를 설명하게 하려는 것이다 — 나중에 「출처 미상」과
--   「사람이 고름」을 구분해야 할 때 지금이 그걸 알 수 있는 유일한 시점이다.
UPDATE customers
   SET assigned_source = 'manual'
 WHERE assigned_employee_id IS NOT NULL
   AND assigned_source IS NULL;

-- 미배정 행은 그대로 NULL — 없는 배정에 출처를 적지 않는다.
--
-- 🚨 기본값(DEFAULT)을 두지 않는 이유: 신규 고객이 **배정도 없이** 'manual'을 달고 태어난다.
--   출처는 배정과 함께 정해지는 값이라 컬럼 기본값으로 만들 수 없다 — 쓰는 쪽(액션)이 짝으로 쓴다.
